#!/usr/bin/env python3
"""The two-track leaderboard (controlled / open), generated from bench/results only.

    python -m bench.leaderboard_tracks                          # bench/leaderboard_tracks.json + Markdown on stdout
    python -m bench.leaderboard_tracks --readme README.md       # also rewrite the block between the tracks markers
    python -m bench.leaderboard_tracks --site website/index.html  # also rewrite the website's leaderboard block

Tracks, their rules, rows and display metadata live in bench/registry/tracks.yaml. Per track and protocol:
a row is shown only when all ten tasks are scored under both protocols; values are compared at the
printed precision; the best value per column is marked (ties included); rows are ordered by their mean
rank over the seven columns (average ranks for ties). Reference rows are printed below and never ranked.
"""
from __future__ import annotations

import argparse
import html
import json
import os
import re
import statistics
from typing import Any, Dict, List, Optional

import yaml

from bench.leaderboard import collect
from bench.registry_io import REPO, load_tasks

TRACKS_YAML = os.path.join(REPO, "bench", "registry", "tracks.yaml")
JSON_OUT = os.path.join(REPO, "bench", "leaderboard_tracks.json")
PROTOS = [("probe", "Frozen probe"), ("finetune", "Fine-tune")]
MARK = ("<!-- tracks:start (generated by python -m bench.leaderboard_tracks; do not edit by hand) -->",
        "<!-- tracks:end -->")


def load_spec() -> Dict[str, Any]:
    with open(TRACKS_YAML) as f:
        return yaml.safe_load(f)


class Board:
    def __init__(self, spec=None, cells=None, tasks=None):
        self.spec = spec or load_spec()
        self.cells = cells if cells is not None else collect()
        self.tasks = tasks or load_tasks()["tasks"]
        self.cols = [dict(task=c[0], label=c[1], unit=c[2], scale=c[3], digits=c[4]) for c in self.spec["columns"]]
        self.har = self.spec["har_mean"]
        self.ten = [c["task"] for c in self.cols if c["task"] != "har_mean"] + self.har

    # -- values ----------------------------------------------------------------
    def raw(self, task: str, enc: str, proto: str) -> Optional[float]:
        c = self.cells.get((task, enc, proto))
        return c.primary()[0] if (c is not None and c.ok) else None

    def value(self, col: Dict[str, Any], enc: str, proto: str) -> Optional[float]:
        if col["task"] == "har_mean":
            vs = [self.raw(t, enc, proto) for t in self.har]
            v = statistics.fmean(vs) if all(x is not None for x in vs) else None
        else:
            v = self.raw(col["task"], enc, proto)
        return None if v is None else round(v * col["scale"], col["digits"])

    def higher_is_better(self, col: Dict[str, Any]) -> bool:
        t = self.har[0] if col["task"] == "har_mean" else col["task"]
        m = self.tasks[t]["metrics"]
        return bool(m[m["primary"]].get("higher_is_better", True))

    def coverage(self, enc: str) -> int:
        return sum(self.raw(t, enc, p) is not None for t in self.ten for p, _ in PROTOS)

    def complete(self, enc: str) -> bool:
        return self.coverage(enc) == 2 * len(self.ten)

    # -- tables ----------------------------------------------------------------
    def track_rows(self, track: str):
        rows = self.spec["tracks"][track]["rows"]
        if isinstance(rows, dict):
            return [(e, dict(m)) for e, m in rows.items()]
        return [(e, {"label": lab}) for e, lab in rows]

    def table(self, track: str, proto: str) -> Dict[str, Any]:
        rows, pending = [], []
        for enc, meta in self.track_rows(track):
            if not self.complete(enc):
                pending.append(dict(encoder=enc, label=meta["label"], cells=self.coverage(enc), of=2 * len(self.ten)))
                continue
            bad = set(meta.get("contaminated") or [])
            rows.append(dict(encoder=enc, meta=meta, label=meta["label"],
                             values=[self.value(c, enc, proto) for c in self.cols],
                             contaminated=[(c["task"] in bad) or (c["task"] == "har_mean" and bool(bad & set(self.har)))
                                           for c in self.cols]))
        # A contaminated cell (the encoder's pretraining saw that task's evaluation data) is printed but
        # takes part in neither the column's best value nor the row's mean rank.
        for j, col in enumerate(self.cols):
            clean = [r for r in rows if not r["contaminated"][j]]
            vs = [r["values"][j] for r in clean]
            hib = self.higher_is_better(col)
            best = (max(vs) if hib else min(vs)) if vs else None
            for r in rows:
                if r["contaminated"][j]:
                    r.setdefault("best", []).append(False)
                    continue
                r.setdefault("best", []).append(r["values"][j] == best)
                better = sum((v > r["values"][j]) if hib else (v < r["values"][j]) for v in vs)
                ties = sum(v == r["values"][j] for v in vs)
                r.setdefault("ranks", []).append(better + (ties + 1) / 2)
        for r in rows:
            r["mean_rank"] = round(statistics.fmean(r["ranks"]), 2) if r.get("ranks") else None
        rows.sort(key=lambda r: (r["mean_rank"], r["label"]))
        refs = []
        for enc, p, lab in self.spec.get("references", []):
            if p not in (proto, "scratch"):
                continue
            vals = [self.value(c, enc, p) for c in self.cols]
            if any(v is not None for v in vals):
                refs.append(dict(encoder=enc, label=lab, values=vals))
        return dict(track=track, protocol=proto, rows=rows, references=refs, pending=pending)

    def all_tables(self) -> Dict[str, Any]:
        return {t: {p: self.table(t, p) for p, _ in PROTOS} for t in self.spec["tracks"]}


# ---------------------------------------------------------------------------
def fmt(v: Optional[float], col: Dict[str, Any]) -> str:
    return "–" if v is None else f"{v:.{col['digits']}f}"


def to_json(board: Board, tables) -> Dict[str, Any]:
    return dict(
        generated_from="bench/results/<task>/<encoder>__<protocol>__s42.json",
        columns=[dict(task=c["task"], label=c["label"], unit=c["unit"],
                      higher_is_better=board.higher_is_better(c)) for c in board.cols],
        har_mean=board.har,
        tracks={t: dict(title=board.spec["tracks"][t]["title"], question=board.spec["tracks"][t]["question"].strip(),
                        rules=board.spec["tracks"][t]["rules"], tables=tables[t])
                for t in board.spec["tracks"]},
        watchlist=board.spec.get("watchlist", []),
        disclosure=board.spec.get("disclosure", ""),
    )


def to_markdown(board: Board, tables) -> str:
    out = []
    for t, spec in board.spec["tracks"].items():
        foot: List[str] = []
        out.append(f"### {spec['title']}\n\n*{spec['question'].strip()}*\n")
        out += [f"- {r}" for r in spec["rules"]]
        out.append("")
        for p, plab in PROTOS:
            tb = tables[t][p]
            head = "| " + " | ".join(["#", plab] + [f"{c['label']} ({c['unit']}) {'↑' if board.higher_is_better(c) else '↓'}"
                                              for c in board.cols] + ["mean rank"]) + " |"
            out += [head, "|" + "---|" * (len(board.cols) + 3)]
            for i, r in enumerate(tb["rows"], 1):
                lab = r["label"]
                if r["meta"].get("weights") == "reproduction":
                    lab += " †"
                elif r["meta"].get("note"):
                    lab += " ‡"
                    foot.append(f"‡ {r['label']}: {r['meta']['note']}.")
                vals = [(fmt(v, c) + " §") if x else (("**" + fmt(v, c) + "**") if b else fmt(v, c))
                        for v, c, b, x in zip(r["values"], board.cols, r["best"], r["contaminated"])]
                if any(r["contaminated"]):
                    foot.append("§ contaminated: the encoder's pretraining data contains this task's evaluation "
                                "data; shown, but not ranked.")
                out.append("| " + " | ".join([str(i), lab] + vals + [f"{r['mean_rank']:.2f}"]) + " |")
            for r in tb["references"]:
                out.append("| | *" + r["label"] + "* | " + " | ".join(f"*{fmt(v, c)}*" for v, c in zip(r["values"], board.cols)) + " | |")
            out.append("")
        pend = tables[t]["probe"]["pending"]
        if pend:
            out.append("Being evaluated: " + "; ".join(f"{x['label']} ({x['cells']}/{x['of']} cells)" for x in pend) + ".\n")
        out += sorted(set(foot), key=foot.index)
        if foot:
            out.append("")
        if t == "open":
            out.append("† No official checkpoint exists; pretrained by us with the authors' code and recipe.\n")
            if board.spec.get("disclosure"):
                out.append("*" + board.spec["disclosure"] + "*\n")
    if board.spec.get("watchlist"):
        out.append("**Not on the board yet:** " + " ".join(f"{w['model']}: {w['status'].strip()}." for w in board.spec["watchlist"]) + "\n")
    return "\n".join(out)


# ---------------------------------------------------------------------------
def esc(s) -> str:
    return html.escape(str(s), quote=False)


def html_table(board: Board, tb, open_track: bool) -> str:
    head = "".join(f"<th>{esc(c['label'])}<small>{esc(c['unit'])} {'&uarr;' if board.higher_is_better(c) else '&darr;'}</small></th>"
                   for c in board.cols)
    out = ['<table class="lb">', f"<thead><tr><th>Encoder</th>{head}<th>Mean rank<small>&darr;</small></th></tr></thead>", "<tbody>"]
    for r in tb["rows"]:
        lab = esc(r["label"])
        m = r["meta"]
        if open_track:
            w = {"official": "released weights", "reproduction": "reproduction&dagger;"}.get(m.get("weights"), esc(m.get("weights", "")))
            link = f' &middot; <a href="{esc(m["url"])}">{w}</a>' if m.get("url") else f" &middot; {w}"
            link += f" &middot; run by {esc(m['run_by'])}" if m.get("run_by") else ""
            note = f" &middot; {esc(m['note'])}" if m.get("note") and m.get("weights") != "reproduction" else ""
            lab += f"<small>{esc(m.get('params', ''))} &middot; {esc(m.get('data', ''))}{link}{note}</small>"
        tds = "".join(('<td class="contam" title="pretraining saw this task\'s evaluation data; not ranked">'
                       + fmt(v, c) + "&sect;</td>") if x else (("<td class=\"b\">" if b else "<td>") + fmt(v, c) + "</td>")
                      for v, c, b, x in zip(r["values"], board.cols, r["best"], r["contaminated"]))
        out.append(f"<tr><td>{lab}</td>{tds}<td>{r['mean_rank']:.2f}</td></tr>")
    for i, r in enumerate(tb["references"]):
        cls = "ref sep" if i == 0 else "ref"
        tds = "".join(f"<td>{fmt(v, c)}</td>" for v, c in zip(r["values"], board.cols))
        out.append(f'<tr class="{cls}"><td>{esc(r["label"])}</td>{tds}<td></td></tr>')
    out += ["</tbody>", "</table>"]
    return "\n".join(out)


def to_html(board: Board, tables) -> str:
    out = ['<div class="tabs" role="tablist" aria-label="Track">']
    for i, (t, spec) in enumerate(board.spec["tracks"].items()):
        out.append(f'<button class="tab" role="tab" aria-selected="{"true" if i == 0 else "false"}" aria-controls="trk-{t}" '
                   f'id="trk-{t}-tab" type="button">{esc(spec["title"])}</button>')
    out.append("</div>")
    for i, (t, spec) in enumerate(board.spec["tracks"].items()):
        out.append(f'<div class="trk" id="trk-{t}" role="tabpanel" aria-labelledby="trk-{t}-tab"{" hidden" if i else ""}>')
        out.append(f'<p class="lb-intro"><strong>{esc(spec["question"].strip())}</strong> ' + " ".join(esc(r) for r in spec["rules"]) + "</p>")
        out.append(f'<div class="tabs" role="tablist" aria-label="Protocol, {esc(spec["title"])}">')
        for j, (p, plab) in enumerate(PROTOS):
            out.append(f'<button class="tab" role="tab" aria-selected="{"true" if j == 0 else "false"}" '
                       f'aria-controls="lb-{t}-{p}" id="tab-{t}-{p}" type="button">{plab}</button>')
        out.append("</div>")
        for j, (p, _) in enumerate(PROTOS):
            out.append(f'<div class="lb-wrap" id="lb-{t}-{p}" role="tabpanel" aria-labelledby="tab-{t}-{p}"{" hidden" if j else ""}>')
            out.append(html_table(board, tables[t][p], open_track=(t == "open")))
            out.append("</div>")
        notes = []
        pend = tables[t]["probe"]["pending"]
        if pend:
            notes.append("Being evaluated: " + "; ".join(f"{esc(x['label'])} ({x['cells']} of {x['of']} cells)" for x in pend) + ".")
        if any(any(r["contaminated"]) for r in tables[t]["probe"]["rows"] + tables[t]["finetune"]["rows"]):
            notes.append("&sect; Contaminated: the encoder's pretraining data contains this task's evaluation data. "
                         "The value is shown but takes part in neither the column's best nor the mean rank.")
        if t == "open" and board.spec.get("disclosure"):
            notes.append(esc(board.spec["disclosure"]))
        if t == "open":
            notes.append("&dagger; No official checkpoint has been released; pretrained by us with the authors' code and recipe, "
                         "and replaced by the official weights when they appear.")
            wl = board.spec.get("watchlist") or []
            if wl:
                notes.append("Not on the board yet: " + " ".join(f"{esc(w['model'])}: {esc(w['status'].strip())}." for w in wl))
        if notes:
            out.append('<p class="lb-note">' + " ".join(notes) + "</p>")
        out.append("</div>")
    return "\n".join(out)


def inject(path: str, block: str) -> None:
    with open(path) as f:
        s = f.read()
    i, j = s.find(MARK[0]), s.find(MARK[1])
    if i < 0 or j < 0:
        raise SystemExit(f"{path}: markers {MARK[0][:20]}... / {MARK[1]} not found")
    s = s[: i + len(MARK[0])] + "\n" + block.rstrip() + "\n" + s[j:]
    with open(path, "w") as f:
        f.write(s)
    print(f"[tracks] wrote {path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=JSON_OUT)
    ap.add_argument("--readme", default=None, help="Markdown file with the tracks markers to rewrite")
    ap.add_argument("--site", default=None, help="website index.html with the tracks markers to rewrite")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()
    board = Board()
    tables = board.all_tables()
    with open(a.json, "w") as f:
        json.dump(to_json(board, tables), f, indent=1, ensure_ascii=False)
    md = to_markdown(board, tables)
    if a.readme:
        inject(a.readme, md)
    if a.site:
        inject(a.site, to_html(board, tables))
    if not a.quiet:
        print(md)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Task-similarity table: are two IMU-Bench tasks solved by similar wrist-IMU representations?

    python analysis/paper_tables/make_task_similarity.py

Two independent views of the same question, both read off the reference InrtlWrist encoder.

Behavioural: fine-tune the InrtlWrist encoder on task A, freeze it, train task B's decoder on top, and
compare with the unadapted InrtlWrist probe on B. The relative change

    rel(A -> B) = (InrtlWrist probe on B  -  A-adapted probe on B) / |InrtlWrist probe on B|      (sign fixed so
                                                                                     positive = better)

says how much A's supervision buys on B beyond generic pretraining; the symmetric mean of the two
directions is the behavioural similarity of the pair. Cells come from bench/results (the transfer
study of Section~\\ref{sec:results_cross_task}).

Representational: CKNNA between the pooled embeddings of the A- and B-adapted encoders on one shared
set of Nymeria probe windows (analysis/task_similarity/cknna_results.csv, written by
analysis/compute_cknna_scratch_encoders.py --encoders ...). This never looks at task performance.

Writes <paper>/Sections/tab_task_similarity.tex and paper_results/tab3_task_similarity/.
"""
import csv
import itertools
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from bench.leaderboard import collect                       # noqa: E402
from bench.registry_io import REPO, load_tasks              # noqa: E402

PAPER = "/gpfs/home/vbc1591/paper_iclr/Sections"
CKNNA_CSV = os.path.join(REPO, "analysis", "task_similarity", "cknna_results.csv")
# source encoder id, its target task id, short label, and the label the CKNNA run uses
PAIRS = [("tx5_fullbody", "full_body_pose_nymeria", "Full-body pose", "Full-body pose"),
         ("tx5_odom", "odometry_nymeria_local", "Odometry", "Odometry"),
         ("tx5_gesture", "microgesture_openwatch", "Microgesture", "Microgesture"),
         ("tx5_pd", "pd_pads", "Parkinson's", "Parkinson's"),
         ("tx5_prism", "har_prism", "PRISM activity", "PRISM"),
         ("tx5_language", "language_humanml3d", "IMU--text", "IMU-text")]
tasks = load_tasks()["tasks"]
cells = collect()


def prim(task, enc, proto):
    c = cells.get((task, enc, proto))
    return c.primary()[0] if (c and c.ok) else None


def rel(src_enc, tgt_task):
    """Relative gain of the src-adapted frozen encoder over the unadapted InrtlWrist probe on tgt_task."""
    base, got = prim(tgt_task, "mae_5src", "probe"), prim(tgt_task, src_enc, "probe")
    if base in (None, 0) or got is None:
        return None
    m = tasks[tgt_task]["metrics"]
    up = bool(m[m["primary"]].get("higher_is_better", True))
    return ((got - base) if up else (base - got)) / abs(base)


def cknna_table():
    """{frozenset({label_a, label_b}): (cknna, cka)} from the representational-similarity run."""
    out = {}
    if not os.path.exists(CKNNA_CSV):
        return out
    with open(CKNNA_CSV) as f:
        for r in csv.DictReader(f):
            out[frozenset((r["task_a"], r["task_b"]))] = (float(r["cknna"]), float(r["cka"]))
    return out


CK = cknna_table()
rows, csv_rows = [], []
for (ea, ta, la, ca), (eb, tb, lb, cb) in itertools.combinations(PAIRS, 2):
    ab, ba = rel(ea, tb), rel(eb, ta)          # A's encoder on B, B's encoder on A
    mean = (ab + ba) / 2 if (ab is not None and ba is not None) else None
    ck = CK.get(frozenset((ca, cb)))
    f = lambda v, p=1: "--" if v is None else f"{100 * v:+.{p}f}"
    rows.append((la, lb, f(ab), f(ba), f(mean),
                 "--" if ck is None else f"{ck[0]:.3f}", "--" if ck is None else f"{ck[1]:.3f}"))
    csv_rows.append([la, lb, ab, ba, mean, ck[0] if ck else None, ck[1] if ck else None])
rows.sort(key=lambda r: (r[4] == "--", -float(r[4]) if r[4] != "--" else 0))

lines = ["% Generated by IMU-SSL/analysis/paper_tables/make_task_similarity.py -- do not edit by hand.",
         r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}",
         r"\caption{Task similarity from the reference InrtlWrist encoder. \emph{Transfer} (\%): the "
         r"relative change of the frozen probe on one task when the encoder has first been fine-tuned on the "
         r"other, against the unadapted InrtlWrist probe on that task; positive means the other task's supervision "
         r"helps. \emph{Sym.} is the mean of the two directions. Pairs are ordered by symmetric transfer.}",
         r"\label{tab:task_similarity}",
         r"\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{%",
         r"\begin{tabular}{@{}llrrr@{}}", r"\toprule",
         r"\multicolumn{2}{@{}l}{Task pair} & \multicolumn{3}{c}{Transfer (\%)} \\",
         r"\cmidrule(lr){3-5}",
         r"A & B & A$\to$B & B$\to$A & Sym. \\", r"\midrule"]
lines += [" & ".join(r[:5]) + r" \\" for r in rows]   # CKNNA/CKA columns dropped 2026-09-23
lines += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table}", ""]
open(os.path.join(PAPER, "tab_task_similarity.tex"), "w").write("\n".join(lines))

sys.path.insert(0, os.path.join(REPO, "paper_results"))
from paper_io import write_csv  # noqa: E402
write_csv("tab3_task_similarity", "task_similarity.csv",
          ["task_a", "task_b", "rel_a_to_b", "rel_b_to_a", "symmetric", "cknna", "cka"], csv_rows)
done = sum(1 for r in rows if r[4] != "--")
print(f"wrote {PAPER}/tab_task_similarity.tex ({done}/{len(rows)} pairs with both transfer directions, "
      f"{len(CK)} CKNNA pairs)")

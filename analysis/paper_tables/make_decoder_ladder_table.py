#!/usr/bin/env python3
"""Section 4 body table: the full-body decoder ladder, MAE against the never-trained frozen encoder.

Reads paper_results/appendix_decoder_controls/decoder_controls.csv and writes
<paper>/Sections/tab_decoder_ladder.tex (added to the main text on 2026-09-23, user request).
"""
import csv
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PAPER = "/gpfs/home/vbc1591/paper_iclr/Sections"
SRC = os.path.join(REPO, "paper_results", "appendix_decoder_controls", "decoder_controls.csv")

# (task variant, row label) in ladder order
LADDER = [("full_body_pose_nymeria_dec0x0", "Linear readout"),
          ("full_body_pose_nymeria", r"1 cross-channel layer, width 192 (benchmark)"),
          ("full_body_pose_nymeria_dec1x0", "1 cross-channel layer, width 384"),
          ("full_body_pose_nymeria_dec1x4", "1 cross-channel + 4 temporal layers, width 384"),
          ("full_body_pose_nymeria_deepdec", "4 cross-channel + 8 temporal layers, width 384")]

v = {}
for r in csv.DictReader(open(SRC)):
    v[(r["encoder"], r["decoder_task_variant"])] = float(r["mpjpe_mm"])

rows = []
for var, lab in LADDER:
    m, rnd = v[("mae_5src", var)], v[("control_random", var)]
    rows.append(rf"{lab} & {m:.1f} & {rnd:.1f} & {rnd - m:.1f} \\")

lines = ["% Generated by IMU-SSL/analysis/paper_tables/make_decoder_ladder_table.py -- do not edit by hand.",
         r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}",
         r"\caption{Full-body pose (MPJPE, mm$\downarrow$) of the frozen MAE and a never-trained frozen encoder of the "
         r"same architecture as the probe decoder grows: the gap that separates them under light decoders all but "
         r"vanishes once the decoder has temporal layers.}",
         r"\label{tab:decoder_ladder}",
         r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
         r"Probe decoder & MAE & Random & Gap \\", r"\midrule"] + rows + \
        [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
out = os.path.join(PAPER, "tab_decoder_ladder.tex")
open(out, "w").write("\n".join(lines))
print("wrote", out)

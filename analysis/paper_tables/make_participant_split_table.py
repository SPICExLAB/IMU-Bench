#!/usr/bin/env python3
"""Appendix table: the kinematic transfer block repeated on disjoint participant thirds.

    python analysis/paper_tables/make_participant_split_table.py [out.tex]

Three Nymeria tasks share one session-disjoint split, so a source encoder trained on one of them has
already seen the target's evaluation participants in other recordings. The p3a/p3b/p3c task cards cut
the participants into three disjoint thirds, one per task. This table puts the frozen cells of the two
splits side by side; only the gains over the never-trained encoder of the SAME split are comparable,
because each third carries a third of the data.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
import json  # noqa: E402

OUT = sys.argv[1] if len(sys.argv) > 1 else "/gpfs/home/vbc1591/paper_iclr/Sections/tab_participant_split.tex"
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# target label, unit, full-split task id, participant-split task id, digits, the two source tasks
BLOCK = [
    ("Arm pose", r"cm\,$\downarrow$", "arm_pose_nymeria", "arm_pose_nymeria_p3a", 2,
     [("fullbody", "full-body pose"), ("odom", "odometry")]),
    ("Full-body pose", r"mm\,$\downarrow$", "full_body_pose_nymeria", "full_body_pose_nymeria_p3b", 1,
     [("armpose", "arm pose"), ("odom", "odometry")]),
    ("Odometry", r"ATE m\,$\downarrow$", "odometry_nymeria_local", "odometry_nymeria_local_p3c", 3,
     [("armpose", "arm pose"), ("fullbody", "full-body pose")]),
]


def val(task, enc, proto):
    p = os.path.join(REPO, "bench", "results", task, f"{enc}__{proto}__s42.json")
    if not os.path.exists(p):
        raise SystemExit(f"missing cell: {task}/{enc}__{proto}")
    d = json.load(open(p))
    if d.get("status") != "ok":
        raise SystemExit(f"cell not ok: {task}/{enc}__{proto}")
    return d["metrics"][d["primary_metric"]]


def gain(v, ref):                       # every kinematic metric is lower-is-better
    return (ref - v) / ref * 100.0


rows = []
for label, unit, t_full, t_p3, dig, srcs in BLOCK:
    r_full, r_p3 = val(t_full, "control_random", "probe"), val(t_p3, "control_random", "probe")
    block = [("never-trained encoder", r_full, None, r_p3, None),
             ("InrtlWrist", val(t_full, "mae_5src", "probe"), r_full, val(t_p3, "mae_5src", "probe"), r_p3)]
    for key, sl in srcs:
        block.append((f"source: {sl}", val(t_full, f"txs_{key}", "probe"), r_full,
                      val(t_p3, f"txs3_{key}", "probe"), r_p3))
    rows.append((label, unit, dig, block))

L = [r"% Generated by IMU-SSL/analysis/paper_tables/make_participant_split_table.py -- do not edit by hand.",
     r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{5pt}",
     r"\caption{The kinematic block of Figure~\ref{fig:transferability_comparison} repeated on three "
     r"disjoint thirds of the Nymeria participants, one per task, so that no encoder has seen a "
     r"participant that another task is evaluated on. Frozen probes only. \emph{Gain} is the "
     r"improvement over the never-trained encoder \emph{of the same split}; the raw metrics of the two "
     r"splits are not comparable, because each third carries a third of the data and every cell, "
     r"source encoders included, is retrained inside it.}",
     r"\label{tab:participant_split}",
     r"\begin{tabular}{@{}llrrrr@{}}", r"\toprule",
     r" & & \multicolumn{2}{c}{session split (Fig.~\ref{fig:transferability_comparison})}"
     r" & \multicolumn{2}{c}{participant split} \\",
     r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
     r"Target & Frozen encoder & metric & gain & metric & gain \\", r"\midrule"]
for i, (label, unit, dig, block) in enumerate(rows):
    if i:
        L.append(r"\midrule")
    for j, (name, vf, rf, vp, rp) in enumerate(block):
        head = f"{label} ({unit})" if j == 0 else ""
        gf = "---" if rf is None else f"${gain(vf, rf):+.1f}$"
        gp = "---" if rp is None else f"${gain(vp, rp):+.1f}$"
        L.append(f"{head} & {name} & {vf:.{dig}f} & {gf} & {vp:.{dig}f} & {gp} \\\\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

open(OUT, "w").write("\n".join(L))
print(f"wrote {OUT} ({sum(len(b[3]) for b in rows)} cells x 2 splits)")

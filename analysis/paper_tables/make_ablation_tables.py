#!/usr/bin/env python3
"""Appendix ablation tables from bench/results (pending cells print "--").

    python analysis/paper_tables/make_ablation_tables.py

tab_decoder_controls.tex  full-body frozen-probe MPJPE for MAE / FOCAL / a random frozen encoder under four
                          probe decoders (linear, 1x0, 1x4, 4x8 = the benchmark decoder)
tab_corpus_budget.tex     frozen-probe results of MAE pretrained on corpora of the same size built by four
                          rules (50K steps), and at 1 % / 100 % of the pool for 50K vs 150K steps
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from bench.leaderboard import collect                       # noqa: E402
from bench.leaderboard_paper import COLS, HAR3              # noqa: E402

PAPER = "/gpfs/home/vbc1591/paper_iclr/Sections"
# ICLR is single-column (5.5 in), so table* buys no width; shrink only if the tabular would otherwise
# run past the text block.
FIT = r"\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{%"
cells = collect()
SCALE = {t: 100 for t in ("microgesture_openwatch", "pd_pads", *HAR3)}
DIG = {"arm_pose_nymeria": 2, "full_body_pose_nymeria": 1, "odometry_nymeria_local": 3, "language_humanml3d": 1}
SHORT = ["Arm", "Body", "Odom.", "Gest.", "Text", "PD", "HHAR", "MHLTH", "PRISM", "User", "HAR"]


def v(task, enc, proto="probe"):
    c = cells.get((task, enc, proto))
    x = c.primary()[0] if c else None
    return None if x is None else x * SCALE.get(task, 1)


def f(task, x):
    return "--" if x is None else f"{x:.{DIG.get(task, 1)}f}"


# ---- decoder capacity x encoder ------------------------------------------------------------------
DECS = [("full_body_pose_nymeria_dec0x0", "linear"), ("full_body_pose_nymeria", "1+0, 192 (benchmark)"),
        ("full_body_pose_nymeria_dec1x0", "1+0"), ("full_body_pose_nymeria_dec1x4", "1+4"),
        ("full_body_pose_nymeria_deepdec", "4+8")]
ENCS = [("mae_5src", "MAE"), ("focal_5src", "FOCAL"), ("control_random", "Random frozen encoder")]
rows = []
for enc, lab in ENCS:
    rows.append(lab + " & " + " & ".join(f("full_body_pose_nymeria", v(t, enc)) for t, _ in DECS) + r" \\")
L = [r"% Generated by IMU-SSL/analysis/paper_tables/make_ablation_tables.py -- do not edit by hand.",
     r"\begin{table}[t]", r"\centering", r"\small",
     r"\caption{Full-body pose MPJPE (mm, $\downarrow$) of frozen encoders read by probe decoders of increasing "
     r"capacity (cross-channel + temporal attention layers; width 384 unless noted). The random frozen encoder has the MAE "
     r"architecture and was never trained; the gap to it at each capacity is what pretraining contributes. "
     r"IMU-Bench uses the light decoder of the original task configuration (1+0, width 192).}",
     r"\label{tab:decoder_controls}",
     r"\begin{tabular}{@{}l" + "r" * len(DECS) + r"@{}}", r"\toprule",
     "Encoder & " + " & ".join(lab for _, lab in DECS) + r" \\", r"\midrule"] + rows + \
    [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
# tab_decoder_controls.tex dropped from the paper on 2026-09-20 (ladder is in prose); CSV still exported below

# ---- corpus construction and budget --------------------------------------------------------------
ARMS = [("corpus_ref", "Reference composition", "197k", "50k"),
        ("corpus_uniform", "Uniform random", "196k", "50k"),
        ("corpus_temp03", "Source temperature ($\\alpha{=}0.3$)", "196k", "50k"),
        ("g5_k1000_f10", "Motion-mode balanced", "196k", "50k"),
        None,
        ("g5_k1000_f1", "Motion-mode balanced, 1\\,\\% of pool", "19.6k", "50k"),
        ("g5_k1000_f1_150k", "Motion-mode balanced, 1\\,\\% of pool", "19.6k", "150k"),
        ("g5_k1000_f100", "Full pool", "1.96M", "50k"),
        ("g5_k1000_f100_150k", "Full pool", "1.96M", "150k")]
tasks = [t for t, _, _ in COLS]
rows = []
for a in ARMS:
    if a is None:
        rows.append(r"\midrule")
        continue
    enc, lab, n, steps = a
    vals = [v(t, enc) for t in tasks]
    har = [vals[tasks.index(h)] for h in HAR3]
    vals.append(sum(har) / len(har) if all(x is not None for x in har) else None)
    rows.append(f"{lab} & {n} & {steps} & " + " & ".join(f((tasks + ['har'])[j], x) for j, x in enumerate(vals)) + r" \\")
L = [r"% Generated by IMU-SSL/analysis/paper_tables/make_ablation_tables.py -- do not edit by hand.",
     r"\begin{table*}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
     r"\caption{Frozen-probe results of MAE pretrained on subsets of the five-source pool. Top: four rules for "
     r"building a corpus of the reference size, all trained for 50,000 steps with the same recipe, cache and "
     r"validation set. Bottom: data volume crossed with training budget. Metrics and units as in the "
     r"per-task tables of Section~\ref{sec:results}; one seed per cell.}",
     r"\label{tab:corpus_budget}",
     FIT,
     r"\begin{tabular}{@{}lrr" + "r" * (len(tasks) + 1) + r"@{}}", r"\toprule",
     r"Corpus & Windows & Steps & " + " & ".join(SHORT) + r" \\", r"\midrule"] + rows + \
    [r"\bottomrule", r"\end{tabular}", "}", r"\end{table*}", ""]
open(os.path.join(PAPER, "tab_corpus_budget.tex"), "w").write("\n".join(L))
# ---- probe-decoder depth (appendix) ---------------------------------------------------------------
from bench.leaderboard_paper import CONTROLLED  # noqa: E402
DEEP = [("arm_pose_nymeria", "Arm pose (cm)"), ("full_body_pose_nymeria", "Full-body pose (mm)"),
        ("odometry_nymeria_local", "Odometry (m)")]
DEPTHS = [("", "bench."), ("_dec2l", "2"), ("_dec4l", "4"), ("_deepdec", "deep")]
ENC_ALL = [(e, l) for e, l, _, _ in CONTROLLED] + [("control_random", "Random frozen encoder"), ("control_raw", "Raw input, 0 layers")]
drows = []
for enc, lab in ENC_ALL:
    drows.append(lab + " & " + " & ".join(f(t, v(t + suf, enc)) for t, _ in DEEP for suf, _ in DEPTHS) + r" \\")
L = [r"% Generated by IMU-SSL/analysis/paper_tables/make_ablation_tables.py -- do not edit by hand.",
     r"\begin{table*}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2.6pt}",
     r"\caption{Frozen probes on the kinematic tasks as the probe decoder deepens. bench.: the benchmark decoder "
     r"(arm pose 2 cross-channel plus 2 temporal layers, full body 1 cross-channel layer, odometry 1 temporal layer, width 192); 2 and 4: decoders with 2 and 4 "
     r"attention layers of the same width (pose: 1 cross-channel plus 1 or 3 temporal layers); deep: pose 4 "
     r"cross-channel plus 8 temporal layers of width 384, odometry 12 layers. With the deep decoder the random "
     r"frozen encoder matches the pretrained ones on pose and beats them on odometry.}",
     r"\label{tab:deep_probe}",
     FIT,
     r"\begin{tabular}{@{}l" + "rrrr" * len(DEEP) + r"@{}}", r"\toprule",
     " & " + " & ".join(r"\multicolumn{4}{c}{" + lab + "}" for _, lab in DEEP) + r" \\",
     " & " + " & ".join(" & ".join(dl for _, dl in DEPTHS) for _ in DEEP) + r" \\", r"\midrule"] + drows + \
    [r"\bottomrule", r"\end{tabular}", "}", r"\end{table*}", ""]
# tab_deep_probe.tex dropped from the paper on 2026-09-20; CSV still exported below
print("wrote tab_corpus_budget.tex (decoder tables dropped from the paper; their CSVs still exported)")

# ---- numbers behind both tables -> paper_results -------------------------------------------------
sys.path.insert(0, os.path.join(os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")), "paper_results"))
from paper_io import write_csv  # noqa: E402


def raw(task, enc, proto="probe"):
    c = cells.get((task, enc, proto))
    return c.primary()[0] if c else None


write_csv("appendix_decoder_controls", "decoder_controls.csv",
          ["encoder", "encoder_label", "decoder_task_variant", "decoder_label", "mpjpe_mm"],
          [[e, el, t, dl, raw(t, e)] for e, el in ENCS for t, dl in DECS])
ab_rows = []
for a in ARMS:
    if a is None:
        continue
    enc, lab, n, steps = a
    for t in tasks:
        ab_rows.append([enc, lab.replace("\\,", " ").replace("\\%", "%").replace("$\\alpha{=}", "alpha=").replace("$", ""),
                        n, steps, t, raw(t, enc)])
write_csv("appendix_corpus_budget", "corpus_budget_long.csv",
          ["encoder", "corpus_label", "windows", "steps", "task", "value"], ab_rows)

write_csv("appendix_deep_probe", "probe_decoder_depth.csv",
          ["encoder", "encoder_label", "task", "benchmark_decoder", "two_layer", "four_layer", "deep"],
          [[e, l, t] + [raw(t + suf, e) for suf, _ in DEPTHS] for e, l in ENC_ALL for t, _ in DEEP])

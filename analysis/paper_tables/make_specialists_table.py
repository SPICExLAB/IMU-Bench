#!/usr/bin/env python3
"""One compact body table: our encoder against the system built for each task.

    python analysis/paper_tables/make_specialists_table.py

Writes <paper>/Sections/tab_specialists.tex. One row per IMU-Bench task, on that task's primary
metric: training from scratch, our MAE frozen and fine-tuned, and the best-scoring published system
for the task retrained under the benchmark's protocol. The full per-task tables (every metric, every
system) are in the appendix; this table exists so the body can make the comparison without them.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
import analysis.paper_tables.make_task_tables as T  # noqa: E402
from bench.leaderboard_paper import COLS            # noqa: E402

OURS = "mae_5src"
PAPER = "/gpfs/home/vbc1591/paper_iclr/Sections"
# Published systems shown per task. Same whitelist rule as the per-task tables: chosen without
# looking at our scores. Odometry's systems were scored under the sibling world-frame task.
ALIAS = T.EXPERT_ALIAS
SHOW = T.EXPERT_SHOW
NAMES = dict(T.EXPERTS)


def experts_for(task):
    """Same rule as the per-task tables: a task's own external cells, and the sibling-protocol rows
    only while it has none of its own."""
    encs = SHOW.get(task, [e for e, _ in T.EXPERTS])
    own = [(e, task) for e in encs if (T.cells.get((task, e, "external")) or None) and T.cells[(task, e, "external")].ok]
    if own or task not in ALIAS:
        return own
    sib, aliased, _ = ALIAS[task]
    return [(e, sib) for e in aliased
            if (T.cells.get((sib, e, "external")) or None) and T.cells[(sib, e, "external")].ok]


def best_expert(task, k):
    hi = T.tasks[task]["metrics"][k].get("higher_is_better", True)
    got = []
    for e, scored_on in experts_for(task):
        v = T.value(scored_on, e, "external", k)
        if v is not None:
            got.append((v, e, scored_on))
    if not got:
        return None, None, None
    v, e, scored_on = (max if hi else min)(got, key=lambda x: x[0])
    suffix = ALIAS[task][2] if scored_on != task else ""
    return v, T.tex(NAMES.get(e, e)) + suffix, scored_on


rows, missing = [], []
for task, name, _ in COLS:
    k = T.tasks[task]["metrics"]["primary"]
    ev, ename, scored_on = best_expert(task, k)
    cells = [T.fmt(task, k, T.value(task, "scratch", "scratch", k)),
             T.fmt(task, k, T.value(task, OURS, "probe", k)),
             T.fmt(task, k, T.value(task, OURS, "finetune", k)),
             (ename or "--"), T.fmt(task, k, ev)]
    if ev is None:
        missing.append(task)
    lab = T.label(task, k, short=True)
    rows.append(f"{T.tex(name).replace(chr(8211), '--')} & {lab} & " + " & ".join(cells) + r" \\")

alias_note = ""
if True:
    alias_note = " TLIO and Air-IO report the epoch with the lowest evaluation ATE, a more favourable rule than the validation-loss selection of the other columns."
caption = (r"Our encoder against the published system built for each task, retrained under this benchmark's protocol "
           r"and scored on the task's primary metric ($\uparrow$/$\downarrow$ give the direction). The task-specific column "
           r"names the better of the systems available for that task; they keep their own inputs, recipes and auxiliary "
           r"components, are untuned here and are listed for orientation, not ranked --- the two pose systems additionally "
           r"read wrist orientation, which the controlled encoders never see." + alias_note +
           r" Parkinson's is ranked here on the window metric; on the per-subject metric the dataset authors' pipeline is "
           r"ahead of every encoder (Section~\ref{sec:results}). Appendix~\ref{app:tasks} gives every metric, every system "
           r"and the remaining caveats (Tables~\ref{tab:task_arm_pose_nymeria}--\ref{tab:task_har}).")

lines = ["% Generated by IMU-SSL/analysis/paper_tables/make_specialists_table.py -- do not edit by hand.",
         r"\begin{table}[t]", r"\centering", r"\footnotesize",
         r"\caption{" + caption + "}", r"\label{tab:specialists}",
         r"\setlength{\tabcolsep}{4pt}",
         r"\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{%",
         r"\begin{tabular}{@{}llrrrlr@{}}", r"\toprule",
         r"Task & Metric & Scratch & \multicolumn{2}{c}{Omni-IMU} & \multicolumn{2}{c}{Task-specific system} \\",
         r"\cmidrule(l){4-5}\cmidrule(l){6-7}",
         r" & & & frozen & fine-tuned & system & score \\", r"\midrule"]
lines += rows
lines += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table}"]
out = os.path.join(PAPER, "tab_specialists.tex")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out, f"({len(rows)} rows)")
if missing:
    print("no task-specific system for:", ", ".join(missing))

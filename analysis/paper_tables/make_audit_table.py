#!/usr/bin/env python3
"""Appendix audit table for OpenWatch, from the file-hash forensics and bench results.

    python analysis/paper_tables/make_audit_table.py

Counts come from analysis/openwatch_forensics/openwatch_contamination_maps.json (byte-identical files,
duplicate identity groups, mirrored augmented ids) and the loader's own discovery (records before/after
exact-file de-duplication). Scores compare the same encoder/protocol on the release's raw-id split
(task microgesture_openwatch_releasesplit, contamination_safe off) and on the canonical-identity split.
"""
import collections
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, REPO)
PAPER = "/gpfs/home/vbc1591/paper_iclr/Sections"
from imu_lm.data.openwatch_loader import canonical_subject, discover_openwatch_records  # noqa: E402

ROOT = "/projects/b53017/vbc1591/openwatch_raw/open_watch_without_augmentations"
m = json.load(open(os.path.join(REPO, "analysis/openwatch_forensics/openwatch_contamination_maps.json")))
groups = m["duplicate_file_groups"]
n_files = sum(len(v) for v in groups.values())
ids_with_dups = collections.Counter(f.split("/")[0] for v in groups.values() for f in v)
raw, _ = discover_openwatch_records(root=ROOT, subjects=None, seed=42)
dedup, _ = discover_openwatch_records(root=ROOT, subjects=None, seed=42, dedup_exact=True)
subj = {r.subject_id for r in raw}
canon = {canonical_subject(s) for s in subj}
aug = m["aug_source_map"]
facts = [
    ("Participant ids in the release", f"{len(subj)}"),
    ("Distinct identities after merging duplicate ids", f"{len(canon)}"),
    ("Duplicate-identity groups (ids)", "; ".join("{" + ", ".join(str(i) for i in g) + "}" for g in m["duplicate_subject_groups"])),
    ("Byte-identical files / groups / ids involved", f"{n_files} / {len(groups)} / {len(ids_with_dups)}"),
    ("Recordings before / after exact de-duplication", f"{len(raw):,} / {len(dedup):,}"),
    ("Augmented ids that are mirrored copies of real ids", f"{len(aug)} of {len(aug)} (ids 51--85; {len(set(aug.values()))} distinct sources)"),
]


def res(task, enc, proto, key="clip_macro_f1"):
    p = os.path.join(REPO, "bench/results", task, f"{enc}__{proto}__s42.json")
    return json.load(open(p))["metrics"].get(key) if os.path.exists(p) else None


def f(x):
    return "--" if x is None else f"{100 * x:.1f}"


score_rows = []
for enc, proto, lab in [("mae_5src", "probe", "WristMAE, frozen probe"), ("mae_5src", "finetune", "WristMAE, fine-tune"),
                        ("scratch", "scratch", "Scratch")]:
    a, b = res("microgesture_openwatch_releasesplit", enc, proto), res("microgesture_openwatch", enc, proto)
    score_rows.append(f"{lab} & {f(a)} & {f(b)} \\\\")
L = [r"% Generated by IMU-SSL/analysis/paper_tables/make_audit_table.py -- do not edit by hand.",
     r"\begin{table}[t]", r"\centering", r"\small",
     r"\caption{OpenWatch release audit. Duplicates are exact: files are grouped by content hash. "
     r"Bottom: clip macro-F1 (\%) on the release's participant-id split, where test id 48 is a byte-identical "
     r"copy of training id 46, and on the canonical-identity split used by IMU-Bench. The two splits have "
     r"different test participants, so the difference mixes leakage with test-set composition "
     r"(per-participant analysis in the text).}",
     r"\label{tab:audit_openwatch}",
     r"\begin{tabular}{@{}lr@{}}", r"\toprule"] + [f"{k} & {v} \\\\" for k, v in facts] + \
    [r"\midrule", r"Clip macro-F1 (\%) & release split / canonical split \\", r"\midrule"] + \
    [r.replace(" & ", " & ", 1).replace(" & ", " / ", 2).replace(" / ", " & ", 1) for r in score_rows] + \
    [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
open(os.path.join(PAPER, "tab_audit_openwatch.tex"), "w").write("\n".join(L))
print("\n".join(f"{k}: {v}" for k, v in facts)); print("\n".join(score_rows))

sys.path.insert(0, os.path.join(REPO, "paper_results"))
from paper_io import write_csv  # noqa: E402
write_csv("appendix_audit_openwatch", "audit_facts.csv", ["item", "value"], facts)
write_csv("appendix_audit_openwatch", "release_vs_canonical_split.csv",
          ["encoder", "protocol", "clip_macro_f1_release_split", "clip_macro_f1_canonical_split"],
          [[e, p, res("microgesture_openwatch_releasesplit", e, p), res("microgesture_openwatch", e, p)]
           for e, p in [("mae_5src", "probe"), ("mae_5src", "finetune"), ("scratch", "scratch")]])

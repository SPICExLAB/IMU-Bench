#!/usr/bin/env python3
"""Every number in the main radar figure (Figure 2), as a markdown file at the repo root.

Reads the two files the radar itself is drawn from -- paper_results/tab2_main_results/radar_normalized.csv
(written by analysis/plot_main_radar.py: raw value, shared per-axis best, relative score) and
main_results_long.csv (the Table 2 cells with their bench/results provenance) -- and writes
main_radar_numbers.md. Never hand-edit the output; rerun after plot_main_radar.py.
"""
import os, datetime
import numpy as np, pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
D = os.path.join(REPO, "paper_results", "tab2_main_results")
OUT = os.path.join(REPO, "main_radar_numbers.md")
r = pd.read_csv(os.path.join(D, "radar_normalized.csv"))
L = pd.read_csv(os.path.join(D, "main_results_long.csv"))
HAR = [("har_hhar", "HHAR"), ("har_mhealth", "MHEALTH"), ("har_prism", "PRISM"), ("har_userwatch", "TransfHAR")]
AXES = [a for a in r.task.drop_duplicates()]                        # radar order
SERIES = [e for e in r.encoder.drop_duplicates()]                  # radar order, Scratch last
LABEL = dict(zip(r.encoder, r.encoder_label)); AXLABEL = dict(zip(r.task, r.task_label)); UNIT = dict(zip(r.task, r.unit))
SCALE = {"F1": 100}; DP = {"cm": 2, "mm": 1, "m": 3, "F1": 1, "R@1": 1}
def fmt(task, v):
    u = UNIT[task]; return "–" if not np.isfinite(v) else f"{v * SCALE.get(u, 1):.{DP[u]}f}"
def cell(task, v, s): return f"{fmt(task, v)} ({s:.2f})"
mtime = datetime.datetime.fromtimestamp(os.path.getmtime(os.path.join(D, "radar_normalized.csv"))).strftime("%Y-%m-%d %H:%M")

o = []
o.append("# Main radar figure (Figure 2): every number\n")
o.append(f"Generated by `analysis/paper_tables/make_radar_numbers.py` from `paper_results/tab2_main_results/radar_normalized.csv` "
         f"(written by `analysis/plot_main_radar.py`, {mtime}) and `main_results_long.csv`. Do not edit by hand.\n")
o.append("Each cell is **raw value (relative score)**. The score is what the radar plots: `v / v_best` for higher-is-better axes and "
         "`v_best / v` for error axes, where `v_best` is the best value on that axis over **both panels, Scratch included** "
         "(shared scale), so 1.00 is the outer ring. F1 values are in %, R@1 in %, errors in the unit shown. "
         "The Activity axis is the mean macro-F1 of the four activity sets; Scratch is the same row in both panels.\n")

o.append("## Axis scale (shared best per axis)\n")
o.append("| Axis | Task | Unit | Direction | Best value | Best cell |\n|---|---|---|---|---|---|")
for t in AXES:
    sub = r[r.task == t]; b = sub.panel_best.iloc[0]; hib = int(sub.higher_is_better.iloc[0])
    w = sub[np.isclose(sub.value, b)].iloc[0]
    o.append(f"| {AXLABEL[t]} | `{t}` | {UNIT[t]} | {'higher' if hib else 'lower'} is better | {fmt(t, b)} | {w.encoder_label}, {w.protocol} |")
o.append("")

for proto, title in [("probe", "Frozen probe (left panel)"), ("finetune", "Fine-tune (right panel)")]:
    o.append(f"## {title}\n")
    o.append("| Encoder | " + " | ".join(f"{AXLABEL[t]} ({UNIT[t]})" for t in AXES) + " |")
    o.append("|---|" + "---|" * len(AXES))
    for e in SERIES:
        sub = r[(r.protocol == proto) & (r.encoder == e)].set_index("task")
        o.append(f"| {LABEL[e]} | " + " | ".join(cell(t, sub.loc[t, 'value'], sub.loc[t, 'score']) for t in AXES) + " |")
    o.append("")

o.append("## Activity axis: the four sets behind the mean (macro-F1, %)\n")
o.append("| Protocol | Encoder | " + " | ".join(n for _, n in HAR) + " | Mean |\n|---|---|" + "---|" * (len(HAR) + 1))
for proto in ["probe", "finetune", "scratch"]:
    for e in SERIES:
        if (e == "scratch") != (proto == "scratch"): continue
        vals = [L.value[(L.encoder == e) & (L.protocol == proto) & (L.task == t)] for t, _ in HAR]
        vals = [float(v.iloc[0]) if len(v) else np.nan for v in vals]
        o.append(f"| {proto} | {LABEL[e]} | " + " | ".join(f"{v * 100:.1f}" for v in vals) + f" | {np.nanmean(vals) * 100:.1f} |")
o.append("")

o.append("## Provenance: the result file behind every cell\n")
o.append("Primary metric of each Table 2 cell that enters the radar (`bench/results/...`, seed 42, one run per cell).\n")
o.append("| Protocol | Encoder | Task | Metric | Value | Result file |\n|---|---|---|---|---|---|")
tasks = [t for t in AXES if t != "__har"] + [t for t, _ in HAR]
for proto in ["probe", "finetune", "scratch"]:
    for e in SERIES:
        if (e == "scratch") != (proto == "scratch"): continue
        for t in tasks:
            row = L[(L.encoder == e) & (L.protocol == proto) & (L.task == t)]
            if not len(row): o.append(f"| {proto} | {LABEL[e]} | `{t}` | – | – | (missing) |"); continue
            row = row.iloc[0]; v = row.value; v = v * 100 if "f1" in str(row.metric).lower() or "acc" in str(row.metric).lower() else v
            o.append(f"| {proto} | {LABEL[e]} | `{t}` | {row.metric} | {v:.3f} | `{row.result_file}` |")
open(OUT, "w").write("\n".join(o) + "\n"); print("wrote", OUT, len(o), "lines")

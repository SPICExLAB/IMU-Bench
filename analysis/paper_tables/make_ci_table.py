#!/usr/bin/env python3
"""Appendix table: 95 % bootstrap intervals for the reference encoder, and the two comparisons the
paper's claims rest on.

    python analysis/paper_tables/make_ci_table.py

Reads bench/results/_bootstrap/summary.json (write it with `python -m bench.bootstrap`), which
resamples the per-unit sidecars every scorer writes. Every cell is one training seed, so an interval
covers evaluation-sample variability only, never seed-to-seed variance; the paired columns resample
the same units for both cells, so they are tighter than the two intervals suggest.

Writes <paper>/Sections/tab_ci.tex and paper_results/appendix_confidence_intervals/.
"""
import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from bench.leaderboard_paper import COLS                    # noqa: E402
from bench.registry_io import REPO, load_tasks              # noqa: E402

PAPER = "/gpfs/home/vbc1591/paper_iclr/Sections"
SUMMARY = os.path.join(REPO, "bench", "results", "_bootstrap", "summary.json")
SCALE = {t: 100 for t in ("microgesture_openwatch", "pd_pads", "har_hhar", "har_mhealth", "har_prism",
                          "har_userwatch")}
DIG = {"arm_pose_nymeria": 2, "full_body_pose_nymeria": 1, "odometry_nymeria_local": 3,
       "language_humanml3d": 1}
# "unit" is the fallback level a scorer reports when no grouping column has >= 10 groups: gesture
# resamples its test clips and the user-study set its windows, both within class strata.
LEVEL = {"participant": "participants", "subject": "subjects", "session": "sessions", "clip": "clips",
         "caption": "captions", "window": "windows"}
UNIT_NAME = {"microgesture_openwatch": "clips", "har_userwatch": "windows"}
tasks = load_tasks()["tasks"]
if not os.path.exists(SUMMARY):
    sys.exit(f"{SUMMARY} not written yet: run `python -m bench.bootstrap`")
S = json.load(open(SUMMARY))
CELLS, PAIRED = S["cells"], S["paired"]


def d(task):
    return DIG.get(task, 1)


def ci(task, cell, diff=False):
    """'point [lo, hi]' in the units the paper reports, or '--'."""
    src = PAIRED if diff else CELLS
    e = src.get(cell)
    if e is None or "error" in e:
        return "--"
    k = "diff" if diff else "point"
    s = SCALE.get(task, 1)
    p, lo, hi = e[k] * s, e["lo"] * s, e["hi"] * s
    star = "" if not diff else ("" if e.get("excludes_zero") else r"$^{\dagger}$")
    return f"{p:+.{d(task)}f} [{lo:+.{d(task)}f}, {hi:+.{d(task)}f}]{star}" if diff else \
           f"{p:.{d(task)}f} [{lo:.{d(task)}f}, {hi:.{d(task)}f}]"


rows, csv_rows = [], []
for t, short, _ in COLS:
    c = CELLS.get(f"{t}/mae_5src__probe__s42") or {}
    raw = c.get("resample_level", "")
    lvl = UNIT_NAME.get(t, LEVEL.get(raw, raw or "--")) if raw == "unit" else LEVEL.get(raw, raw or "--")
    units = f"{c.get('n_groups', '--')} {lvl}" + (", stratified" if c.get("stratified") else "")
    probe = ci(t, f"{t}/mae_5src__probe__s42")
    ft = ci(t, f"{t}/mae_5src__finetune__s42")
    scr = ci(t, f"{t}/scratch__scratch__s42")
    vs_rand = ci(t, f"{t}/mae_5src__probe__s42 - {t}/control_random__probe__s42", diff=True)
    vs_scr = ci(t, f"{t}/mae_5src__finetune__s42 - {t}/scratch__scratch__s42", diff=True)
    rows.append((short, units, probe, ft, scr, vs_rand, vs_scr))
    csv_rows.append([t, c.get("n_groups"), c.get("resample_level"),
                     c.get("point"), c.get("lo"), c.get("hi"),
                     (CELLS.get(f"{t}/mae_5src__finetune__s42") or {}).get("point"),
                     (CELLS.get(f"{t}/scratch__scratch__s42") or {}).get("point")])

lines = ["% Generated by IMU-SSL/analysis/paper_tables/make_ci_table.py -- do not edit by hand.",
         r"\begin{table*}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
         r"\caption{95\,\% percentile bootstrap intervals (1,000 resamples of the evaluation units named in "
         r"the second column) for the reference WristMAE encoder and the from-scratch reference, and the two "
         r"differences the paper's claims rest on. The paired columns resample the same units for both cells, "
         r"so they are tighter than a comparison of the two intervals would suggest; $\dagger$ marks a "
         r"difference whose interval contains zero. Units as in the per-task tables of "
         r"Section~\ref{sec:results}. Every cell is one training seed, so these intervals cover "
         r"evaluation-sample variability and say nothing about seed-to-seed variance.}",
         r"\label{tab:ci}",
         r"\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{%",
         r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
         r"Task & Resampled & WristMAE, frozen probe & WristMAE, fine-tuned & Scratch & "
         r"Probe $-$ random enc. & Fine-tune $-$ scratch \\", r"\midrule"]
lines += [" & ".join(r) + r" \\" for r in rows]
lines += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table*}", ""]
open(os.path.join(PAPER, "tab_ci.tex"), "w").write("\n".join(lines))

sys.path.insert(0, os.path.join(REPO, "paper_results"))
from paper_io import write_csv  # noqa: E402
write_csv("appendix_confidence_intervals", "ci_main.csv",
          ["task", "n_groups", "resample_level", "mae_probe", "mae_probe_lo", "mae_probe_hi",
           "mae_finetune", "scratch"], csv_rows)
n_pair = sum(1 for r in rows if r[5] != "--") + sum(1 for r in rows if r[6] != "--")
print(f"wrote {PAPER}/tab_ci.tex ({len(rows)} tasks, {n_pair} paired comparisons)")

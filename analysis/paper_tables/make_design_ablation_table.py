#!/usr/bin/env python
"""Design-ablation table for the appendix (app:design_ablation).

Each arm changes ONE factor of the reference-corpus arm `corpus_ref` (the full model at the same corpus and 50,000
steps) and is scored with the benchmark's frozen probes on all ten tasks. Differences are read against corpus_ref with
the grouped bootstrap of bench.bootstrap (same per-unit sidecars as Appendix C), and a bold entry is one whose 95 %
interval excludes zero.

    python analysis/paper_tables/make_design_ablation_table.py [out.tex]
"""
import json, os, subprocess, sys
import yaml

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, REPO)
OUT = sys.argv[1] if len(sys.argv) > 1 else "/gpfs/home/vbc1591/paper_iclr/Sections/tab_design_ablation.tex"
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "design_ablation_boot.json")

from bench.leaderboard_paper import COLS                               # noqa: E402
T = yaml.safe_load(open(os.path.join(REPO, "bench/registry/tasks.yaml")))["tasks"]
TASKS = [t for t, _, _ in COLS]
PM = {t: T[t]["metrics"]["primary"] for t in TASKS}
HIB = {t: T[t]["metrics"][PM[t]]["higher_is_better"] for t in TASKS}
FMT = {t: T[t]["metrics"][PM[t]].get("fmt", "{:.3f}") for t in TASKS}
# The fixed-length arm was dropped (user decision 2026-09-22): only 3 of its 10 probes ever ran, and a row scored on
# three tasks cannot be compared with the others. Its pretrain and the three cells stay in bench/results.
ARMS = [("abl_norot", "no rotation augmentation"), ("abl_so3", "$SO(3)$ rotation"),
        ("abl_nozscore", "physical units, no z-score")]
REF = "corpus_ref"


def metric(task, cell):
    p = os.path.join(REPO, "bench/results", task, f"{cell}__s42.json")
    if not os.path.exists(p):
        return None
    r = json.load(open(p))
    return r["metrics"].get(PM[task]) if r.get("status") == "ok" else None


def boot(task, arm, cache):
    """Bootstrap CI of ref - arm, cached on disk (each call is ~30 s of CPU)."""
    key = f"{task}/{arm}"
    if key in cache:
        return cache[key]
    out = subprocess.run([sys.executable, "-m", "bench.bootstrap", "--pair", task,
                          f"{REF}__probe__s42", f"{arm}__probe__s42", "--no-pairs"],
                         capture_output=True, text=True, cwd=REPO, timeout=1800).stdout
    try:
        d = json.loads(out[out.index("{"):out.rindex("}") + 1])
    except ValueError:
        return None
    cache[key] = {"diff": d["diff"], "lo": d["bca_lo"], "hi": d["bca_hi"], "sig": d["excludes_zero"]}
    json.dump(cache, open(CACHE, "w"), indent=1)
    return cache[key]


cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
UP, DOWN = "\\,$\\uparrow$", "\\,$\\downarrow$"
head = " & ".join(lab + (UP if HIB[t] else DOWN) for t, lab, _ in COLS)
L = ["% Generated by IMU-SSL/analysis/paper_tables/make_design_ablation_table.py -- do not edit by hand.",
     "\\begin{tabular}{@{}l" + "r" * len(TASKS) + "@{}}", "\\toprule",
     f"Pretraining arm & {head} \\\\", "\\midrule"]
row = ["Reference (full model)"]
for t in TASKS:
    v = metric(t, f"{REF}__probe")
    row.append("--" if v is None else FMT[t].format(v))
L.append(" & ".join(row) + " \\\\")
L.append("\\midrule")
n_sig = {}
for arm, lab in ARMS:
    row, sig = [lab], []
    for t in TASKS:
        v = metric(t, f"{arm}__probe")
        if v is None:
            row.append("--"); continue
        b = boot(t, arm, cache)
        s = FMT[t].format(v)
        if b and b["sig"]:
            better = (b["diff"] < 0) if HIB[t] else (b["diff"] > 0)
            sig.append((t, better))
            s = "\\textbf{" + s + "}" if better else "\\underline{" + s + "}"
        row.append(s)
    n_sig[arm] = sig
    L.append(" & ".join(row) + " \\\\")
L += ["\\bottomrule", "\\end{tabular}"]
open(OUT, "w").write("\n".join(L) + "\n")
print(f"wrote {OUT}")
for arm, lab in ARMS:
    b = [t for t, ok in n_sig[arm] if ok]; w = [t for t, ok in n_sig[arm] if not ok]
    print(f"  {lab:<32} better than ref: {b}  worse: {w}")

#!/usr/bin/env python3
"""Harvest the frame-match ablation -> analysis/frame_match_ablation.md.

    python analysis/harvest_frame_match.py

Reads ONLY bench/results/*.json (no hand-typed numbers) and lays the cells out as
the 3 x 2 design they were run as:

    rows    pretraining frame  : canon (none) / oct (24 cube rots) / so3 (uniform SO(3))
                                 + reference rows mae_recipe_r0 and scratch
    columns downstream frame   : native / rot7 (one fixed random SO(3) rotation)

The number that answers the question is the LAST column, "frame cost" = how much
the primary metric degrades when the downstream frame is rotated. If pretraining
frame does not matter, every row's cost is the same. If it does, `canon` pays a
cost the rotation-augmented arms do not.
"""
import json, os, sys, statistics

sys.path.insert(0, "/gpfs/home/vbc1591/IMU-SSL"); os.chdir("/gpfs/home/vbc1591/IMU-SSL")
from bench.registry_io import load_tasks

TASKS = ["arm_pose_nymeria", "microgesture_openwatch", "har_wisdm", "har_pamap2"]
ROWS = [("mae_frame_canon", "probe",   "canon  (no rotation)"),
        ("mae_frame_oct",   "probe",   "oct    (24 cube rotations)"),
        ("mae_frame_so3",   "probe",   "so3    (uniform SO(3))"),
        ("mae_recipe_r0",   "probe",   "R0     (production, 514 h, octahedral)"),
        ("scratch",         "scratch", "scratch (no pretraining)")]


def read(task, enc, proto):
    p = f"bench/results/{task}/{enc}__{proto}__s42.json"
    if not os.path.exists(p):
        return None
    r = json.load(open(p))
    if r.get("status") not in (None, "ok"):
        return None
    return r


def main():
    tasks = load_tasks()["tasks"]
    out = ["# Frame-match ablation — does the pretraining coordinate frame have to match?",
           "",
           "Generated by `analysis/harvest_frame_match.py` from `bench/results/*.json`.",
           "",
           "**Design.** Three MAE encoders, pretrained on the *same* 200 h OCDetect-only cache for the",
           "same 30k steps with the same seed; the only key that differs between them is",
           "`random_rotation`. Each is then frozen and probed on four tasks in two downstream",
           "frames: the task's native frame, and `rot7` — the identical task with one fixed random",
           "SO(3) rotation applied to the raw window in *every* split (`frame_perturb`, seed 7).",
           "",
           "**Reading it.** `frame cost` is the native→rot7 change in the task's primary metric,",
           "signed so that **negative is worse**. Pretraining frame matters iff the rows disagree.",
           "",
           "**The `scratch` row is the null model and calibrates the noise floor.** It has no",
           "pretrained frame to mismatch — it re-learns everything from random init on whichever",
           "frame it is handed — so its true frame cost is zero by construction, and whatever",
           "spread it shows is run-to-run noise. Only treat another row's cost as real if it is",
           "clearly outside the scratch row's spread.",
           ""]

    costs = {enc: [] for enc, _, _ in ROWS}
    for t in TASKS:
        card = tasks[t]
        pm = card["metrics"]["primary"]
        hib = bool(card["metrics"][pm].get("higher_is_better", True))
        fmt = card["metrics"][pm].get("fmt", "{:.3f}")
        label = card["metrics"][pm].get("label", pm)
        out += [f"## {card['name']} — {label} ({'higher' if hib else 'lower'} is better)", "",
                "| pretraining frame | native | rot7 (fixed SO(3)) | frame cost | rel. |",
                "|---|---|---|---|---|"]
        for enc, proto, name in ROWS:
            a, b = read(t, enc, proto), read(f"{t}_rot7", enc, proto)
            va = a["metrics"].get(pm) if a else None
            vb = b["metrics"].get(pm) if b else None
            if va is None or vb is None:
                out.append(f"| `{name}` | {fmt.format(va) if va is not None else '—'} | "
                           f"{fmt.format(vb) if vb is not None else '—'} | — | — |")
                continue
            delta = (vb - va) if hib else (va - vb)      # negative = rotation hurt
            rel = delta / abs(va) if va else float("nan")
            costs[enc].append(rel)
            out.append(f"| `{name}` | {fmt.format(va)} | {fmt.format(vb)} | "
                       f"{delta:+.4f} | {rel:+.1%} |")
        out.append("")

    out += ["## Summary — mean relative frame cost across the four tasks", "",
            "| pretraining frame | mean rel. cost | tasks scored |", "|---|---|---|"]
    for enc, _, name in ROWS:
        c = costs[enc]
        out.append(f"| `{name}` | {statistics.fmean(c):+.1%} | {len(c)}/{len(TASKS)} |"
                   if c else f"| `{name}` | — | 0/{len(TASKS)} |")
    out += ["",
            "### Caveats that travel with these numbers",
            "",
            "* The pool is OCDetect **only** (200.0 hop-hours). A single source is what makes the",
            "  pretraining frame well-defined at all: measured mean-gravity axis in the 514 h",
            "  multi-source pool is −Y for OCDetect, −X for SONIC/MotionX, +Z for TotalCapture and",
            "  EatingSpeed, and uniformly spread for NHANES — the `*_FLU` loaders do not agree with",
            "  one another, so a multi-source \"canonical frame\" arm would not have been canonical.",
            "* These encoders see 200 h and 30k steps, so their absolute numbers sit below the",
            "  production 514 h rows. Compare **within** a column, and compare costs **across** rows;",
            "  do not read the absolute values against the main leaderboard.",
            "* `rot7` is ONE draw of a random rotation. A single R can be lucky; treat a difference",
            "  between rows as real only if it is much larger than the between-task spread, or",
            "  re-run the rotated column with a second `frame_perturb.seed`.",
            "* Preprocessing z-scores each channel per window, so a rotation changes both the axis",
            "  geometry *and* the per-channel normalisation. That is what a differently-mounted",
            "  device actually does to this pipeline; it is not a pure geometric rotation of the input.",
            "* The OCDetect cache for this ablation uses `flu_convention: documented` — the real",
            "  Android→FLU rotation applied to acc and gyro alike. Every other cache in the repo",
            "  uses the legacy transform, which mirrors acc (det = −1) and leaves gyro alone.",
            ""]

    open("analysis/frame_match_ablation.md", "w").write("\n".join(out))
    print("wrote analysis/frame_match_ablation.md")
    done = sum(1 for t in TASKS for enc, proto, _ in ROWS
               for tt in (t, f"{t}_rot7") if read(tt, enc, proto))
    print(f"cells scored: {done}/{len(TASKS) * len(ROWS) * 2}")


if __name__ == "__main__":
    main()

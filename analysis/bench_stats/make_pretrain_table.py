#!/usr/bin/env python
"""Pretraining-corpus table for the paper (5-source reference corpus + the larger scaling pool).

    python analysis/bench_stats/make_pretrain_table.py [out.tex]

Reference corpus = what mae_5src and every 5-source baseline actually trained on: the cached arrays in
/projects/b53017/vbc1591/mae_multidata_cache (confirmed from the training logs: combined train=197,094,
val=27,463). Scaling pool = the same five sources in the v3 cache (mae_multidata_cache_v3), used by the
motion-type x volume grid and the coverage analysis; per-source counts from the grid's pool manifest.
Hours = windows x 5.12 s (10.24 s windows at 50 % overlap).
"""
import json
import os
import sys

import numpy as np

OUT = sys.argv[1] if len(sys.argv) > 1 else "/gpfs/home/vbc1591/paper_iclr/Sections/tab_pretrain_corpus.tex"
V1 = "/projects/b53017/vbc1591/mae_multidata_cache"
MANIFEST = "/projects/b53017/vbc1591/diversity_saturation/pool_manifest.json"
HOP_S = 5.12
SOURCES = [("realdata", "HAR sets$^\\dagger$", "real"), ("ocdetect", "OCDetect", "real"),
           ("eatingspeed", "EatingSpeed", "real"), ("motionx", "Motion-X", "syn."), ("sonic", "SONIC", "syn.")]


def n_windows(src, split):
    return int(np.load(os.path.join(V1, f"{src}_{split}_x.npy"), mmap_mode="r").shape[0])


man = json.load(open(MANIFEST))
cum = [0] + man["cumulative_sizes"]
v3 = {s: cum[i + 1] - cum[i] for i, s in enumerate(man["sources"])}

rows, tot_tr, tot_va, tot_v3 = [], 0, 0, 0
for key, name, kind in SOURCES:
    tr, va = n_windows(key, "train"), n_windows(key, "val")
    tot_tr += tr; tot_va += va; tot_v3 += v3[key]
    rows.append((name, kind, tr, tr * HOP_S / 3600, v3[key]))
assert tot_tr == 197094 and tot_va == 27463, (tot_tr, tot_va)   # must match the training logs
assert tot_v3 == 1959288, tot_v3                                 # must match the grid pool

L = [r"% Generated by IMU-SSL/analysis/bench_stats/make_pretrain_table.py -- edit the script, not this file.",
     r"\begin{tabular}{@{}llrrr@{}}", r"\toprule",
     r"Source & Type & Windows & Hours & Scaling pool \\", r"\midrule"]
for name, kind, tr, h, s3 in rows:
    L.append(f"{name} & {kind} & {tr:,} & {h:,.1f} & {s3:,} \\\\")
L += [r"\midrule",
      f"Total & & {tot_tr:,} & {tot_tr * HOP_S / 3600:,.1f} & {tot_v3:,} \\\\",
      r"\bottomrule", r"\end{tabular}", "",
      r"\captionof{table}{Reference pretraining corpus (five sources, accelerometer and gyroscope). "
      f"All self-supervised models are trained on the same {tot_tr:,} training windows "
      f"({tot_va:,} held out for validation) of 10.24\\,s; hours count the 5.12\\,s stride. "
      r"The scaling analysis draws from a larger pool of the same sources (last column). "
      r"$^\dagger$WISDM, PAMAP2, RecoFit, SAMoSA, Shoaib and UT-Watch (UTD-MHAD is in the pool, but its "
      r"clips are shorter than one window and contribute none), none of which is an IMU-Bench evaluation "
      r"set (Table~\ref{tab:imubench_tasks}).}",
      r"\label{tab:pretraining_data_composition}", ""]
open(OUT, "w").write("\n".join(L))
print(f"wrote {OUT}")
for r in rows:
    print("  ", r)
print("   total", tot_tr, tot_va, round(tot_tr * HOP_S / 3600, 1), tot_v3, round(tot_v3 * HOP_S / 3600, 1))

sys.path.insert(0, os.path.join(os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")), "paper_results"))
from paper_io import write_csv  # noqa: E402
write_csv("appendix_pretrain_corpus", "pretrain_corpus.csv",
          ["source", "type", "train_windows", "hours_5p12s_stride", "scaling_pool_windows"],
          [[r[0].replace("$^\\dagger$", " (7 public HAR sets)")] + list(r[1:]) for r in rows])
